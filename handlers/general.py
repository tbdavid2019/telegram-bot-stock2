# Prompt cache to keep Telegram callback_data strictly <= 64 bytes
PROMPT_CACHE: dict[str, str] = {}


def cache_prompt(prompt_text: str) -> str:
    """Cache prompt text and return short key for Telegram callback_data (<= 64 bytes limit)."""
    h = hashlib.md5(prompt_text.encode("utf-8")).hexdigest()[:12]
    key = f"p:{h}"
    PROMPT_CACHE[key] = prompt_text
    return key


def get_cached_prompt(key: str) -> str:
    """Retrieve original prompt text by short key."""
    return PROMPT_CACHE.get(key, key)


def extract_primary_subject(user_input: str, response_text: str = "") -> dict:
    """Extract primary stock ticker or macro topic from input/response as a heuristic fallback."""
    text = (user_input + " " + (response_text[:300] if response_text else "")).strip()

    # 1. Match Taiwan stock codes (e.g. 2330, 2330.TW, 3293.TWO)
    tw_match = re.search(r"\b(\d{4,6}(?:\.TW|\.TWO)?)\b", text, re.IGNORECASE)
    if tw_match:
        code = tw_match.group(1).upper()
        return {"type": "stock", "ticker": code}

    # 2. Match US tickers (2-5 uppercase letters)
    us_match = re.search(r"\b([A-Z]{2,5})\b", user_input)
    if us_match and us_match.group(1) not in (
        "AI", "DCF", "PE", "EPS", "WACC", "FCF", "SEPA", "VCP", "SPY", "USD", "TOC", "API"
    ):
        return {"type": "stock", "ticker": us_match.group(1)}

    # 3. Match known Chinese company names
    company_map = {
        "台積電": "2330.TW", "聯發科": "2454.TW", "鴻海": "2317.TW", "長榮": "2603.TW",
        "鈊象": "3293.TWO", "元太": "8069.TWO", "特斯拉": "TSLA", "輝達": "NVDA", "蘋果": "AAPL",
        "微軟": "MSFT", "谷歌": "GOOGL", "亞馬遜": "AMZN", "博通": "AVGO", "超微": "AMD"
    }
    for name, sym in company_map.items():
        if name in text:
            return {"type": "stock", "ticker": sym, "name": name}

    # 4. Match macro keywords
    macro_keywords = ["降息", "升息", "通膨", "聯準會", "關稅", "非農", "地緣政治", "油價", "美債", "日圓", "AI產業"]
    for kw in macro_keywords:
        if kw in text:
            return {"type": "macro", "topic": kw}

    return {"type": "general"}


def generate_followup_keyboard(
    user_input: str,
    response_text: str = "",
    dynamic_followups: list[str] = None
) -> InlineKeyboardMarkup:
    """
    Dynamically generate contextual follow-up prompt buttons.
    Prioritizes real, bespoke prompts generated by the LLM based on conversation context.
    """
    buttons = []

    # 1. First priority: Contextual follow-up suggestions generated by LLM
    if dynamic_followups and len(dynamic_followups) > 0:
        for prompt in dynamic_followups[:4]:
            prompt_str = prompt.strip()
            if prompt_str:
                label = prompt_str if len(prompt_str) <= 30 else prompt_str[:28] + "..."
                key = cache_prompt(prompt_str)
                buttons.append([InlineKeyboardButton(label, callback_data=key)])
        if buttons:
            return InlineKeyboardMarkup(buttons)

    # 2. Fallback heuristic buttons if LLM omitted dynamic tags
    subj = extract_primary_subject(user_input, response_text)
    if subj["type"] == "stock":
        sym = subj["ticker"]
        is_tw = ".TW" in sym or ".TWO" in sym or sym.isdigit()
        clean_code = sym.replace(".TW", "").replace(".TWO", "")

        if is_tw:
            buttons.append([
                InlineKeyboardButton(f"🏢 查 {clean_code} 三大法人籌碼", callback_data=cache_prompt(f"/chip {sym}")),
                InlineKeyboardButton(f"💰 計算 {clean_code} DCF 合理價", callback_data=cache_prompt(f"/val {sym}"))
            ])
            buttons.append([
                InlineKeyboardButton(f"📐 檢驗 {clean_code} SEPA 趨勢", callback_data=cache_prompt(f"/sepa {sym}")),
                InlineKeyboardButton(f"🏛️ 14 大師圓桌辯論", callback_data=cache_prompt(f"/ai2 {sym}"))
            ])
        else:
            buttons.append([
                InlineKeyboardButton(f"💰 計算 {sym} DCF 內在價值", callback_data=cache_prompt(f"/val {sym}")),
                InlineKeyboardButton(f"📐 檢驗 {sym} SEPA 趨勢", callback_data=cache_prompt(f"/sepa {sym}"))
            ])
            buttons.append([
                InlineKeyboardButton(f"📊 {sym} 多因子風險歸因", callback_data=cache_prompt(f"/ff {sym}")),
                InlineKeyboardButton(f"🏛️ 14 大師圓桌辯論", callback_data=cache_prompt(f"/ai2 {sym}"))
            ])

    elif subj["type"] == "macro":
        topic = subj["topic"]
        buttons.append([
            InlineKeyboardButton(f"⛓️ 分析「{topic}」金融傳導鏈", callback_data=cache_prompt(f"/chain {topic}")),
            InlineKeyboardButton("🔥 查看全球重大快訊", callback_data=cache_prompt("/hot"))
        ])
        buttons.append([
            InlineKeyboardButton("🏢 查台積電 2330 法人籌碼", callback_data=cache_prompt("/chip 2330.TW")),
            InlineKeyboardButton("📊 輝達 NVDA 多因子模型", callback_data=cache_prompt("/ff NVDA"))
        ])

    else:
        buttons.append([
            InlineKeyboardButton("🔥 查看即時重大快訊", callback_data=cache_prompt("/hot")),
            InlineKeyboardButton("🏢 台積電 2330 法人籌碼", callback_data=cache_prompt("/chip 2330.TW"))
        ])
        buttons.append([
            InlineKeyboardButton("📊 輝達 NVDA 多因子歸因", callback_data=cache_prompt("/ff NVDA")),
            InlineKeyboardButton("💰 特斯拉 TSLA DCF估值", callback_data=cache_prompt("/val TSLA"))
        ])

    return InlineKeyboardMarkup(buttons)


