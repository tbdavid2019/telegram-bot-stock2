async def default_message_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Handle regular text messages by passing them to the Main LLM Agent.
    Generates dynamic, context-aware follow-up prompt buttons tailored to the discussion.
    """
    user_input = update.message.text
    if not user_input:
        return

    # Notify user that bot is typing and send temporary status message
    await context.bot.send_chat_action(chat_id=update.effective_chat.id, action="typing")
    processing_msg = await update.message.reply_text("⏳ 思考與處理中，請稍候...")

    try:
        # Process message via Main Agent with conversation memory
        thread_id = str(update.effective_chat.id)
        raw_response = await process_chat_message(user_input, thread_id=thread_id)

        # Delete the temporary processing message
        try:
            await processing_msg.delete()
        except Exception:
            pass

        if not raw_response or not str(raw_response).strip():
            raw_response = "⚠️ 系統分析完成，但未生成文字回覆，請嘗試重新提問或使用專屬指令（如 /val、/sepa、/chain）。"

        clean_response, followups = extract_followups_from_text(raw_response)
        followup_markup = generate_followup_keyboard(user_input, clean_response, dynamic_followups=followups)

        try:
            await update.message.reply_text(clean_response, reply_markup=followup_markup, parse_mode="Markdown")
        except Exception:
            await update.message.reply_text(clean_response, reply_markup=followup_markup)
    except Exception as e:
        logger.error(f"Default message handler error: {e}")
        try:
            await processing_msg.delete()
        except Exception:
            pass
        await update.message.reply_text(f"❌ 處理訊息時發生錯誤：{str(e)}")


async def callback_prompt_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Handle clicks on dynamic follow-up prompt buttons.
    Dispatches slash commands or triggers an organic follow-up analysis with LLM.
    """
    query = update.callback_query
    await query.answer()

    data = query.data or ""
    prompt_text = get_cached_prompt(data) if data.startswith("p:") else (
        data[len("prompt:"):].strip() if data.startswith("prompt:") else data
    )

    if not prompt_text:
        return

    # Dispatch commands if prompt is a direct slash command
    if prompt_text.startswith("/"):
        parts = prompt_text.split()
        cmd = parts[0].lower()
        args = parts[1:]
        context.args = args

        if cmd == "/chip":
            from handlers.stock_cmds import institutional_chip_analysis
            await institutional_chip_analysis(update, context)
            return
        elif cmd == "/val":
            from handlers.stock_cmds import valuation_analysis
            await valuation_analysis(update, context)
            return
        elif cmd == "/sepa":
            from handlers.stock_cmds import sepa_analysis
            await sepa_analysis(update, context)
            return
        elif cmd == "/earn":
            from handlers.stock_cmds import earnings_briefing
            await earnings_briefing(update, context)
            return
        elif cmd == "/corr":
            from handlers.stock_cmds import correlation_analysis
            await correlation_analysis(update, context)
            return
        elif cmd == "/ff":
            from handlers.stock_cmds import fama_french_analysis
            await fama_french_analysis(update, context)
            return
        elif cmd == "/ai2":
            from handlers.ai_cmds import ai2_analysis
            await ai2_analysis(update, context)
            return
        elif cmd == "/chain":
            from handlers.stock_cmds import chain_analysis
            await chain_analysis(update, context)
            return
        elif cmd == "/hot":
            from handlers.stock_cmds import hot_news_query
            await hot_news_query(update, context)
            return
        elif cmd == "/n" or cmd == "/ny":
            from handlers.stock_cmds import stock_news
            await stock_news(update, context)
            return

    # Natural language prompt: feed back to LLM agent with conversation context
    thread_id = str(update.effective_chat.id)
    processing_msg = await query.message.reply_text(
        f"💬 *已選擇續問：* `{prompt_text}`\n⏳ 深度分析中，請稍候...",
        parse_mode="Markdown"
    )
    try:
        raw_response = await process_chat_message(prompt_text, thread_id=thread_id)
        try:
            await processing_msg.delete()
        except Exception:
            pass

        clean_response, followups = extract_followups_from_text(raw_response)
        followup_markup = generate_followup_keyboard(prompt_text, clean_response, dynamic_followups=followups)

        try:
            await query.message.reply_text(clean_response, reply_markup=followup_markup, parse_mode="Markdown")
        except Exception:
            await query.message.reply_text(clean_response, reply_markup=followup_markup)
    except Exception as e:
        logger.error(f"Callback prompt handler error: {e}")
        try:
            await processing_msg.delete()
        except Exception:
            pass
        await query.message.reply_text(f"❌ 處理續問時發生錯誤：{str(e)}")


